// Bake the approved Cloud pearl once; the shipping app never runs the experiment renderer.
import { writeFileSync } from 'node:fs';
import { renderPlanet } from './index.mjs';
import { png } from '../spheres/png.mjs';

const recipe = { version: 2, seed: 23, surface: 'cloud-pearl', layer: 'none', palette: 'ice' };
const art = renderPlanet(recipe, 292);
// Remove the study's presentation padding, so the sphere fills a circular avatar.
const size = 256, inset = (art.width - size) / 2;
const pixels = new Uint8ClampedArray(size * size * 4);
for (let y = 0; y < size; y++) {
  const start = ((y + inset) * art.width + inset) * 4;
  pixels.set(art.data.subarray(start, start + size * 4), y * size * 4);
}
const url = `data:image/png;base64,${png(size, size, pixels).toString('base64')}`;
writeFileSync(new URL('../../../src/shared/cloud-pearl.ts', import.meta.url),
  `// Approved Cloud pearl placeholder. Generated by design/experiments/planet-surfaces/bake-placeholder.mjs.\n` +
  `// Fixed recipe: ${JSON.stringify(recipe)}. No runtime rendering or network requests.\n` +
  `export const CLOUD_PEARL_URL = '${url}';\n`);
console.log(`Baked Cloud pearl: ${size}×${size}, ${Math.round(url.length / 1024)} KB bundled data URL`);
